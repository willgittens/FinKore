import { AuditEvent } from './audit-event.js'
import { auditEventMatchesRedactionPolicy, redactAuditEvent, validateAuditRedactionPolicy } from './audit-redaction.js'
import { AuditAppendOnlyViolationError, DuplicateAuditEventError, InvalidAuditRedactionError } from './errors.js'
import type { AuditRedactionRequest, AuditRedactionResult, SerializedAuditEvent, SerializedAuditHistory } from './types.js'

/**
 * FinKore Audit Log for append-only history semantics.
 *
 * The log commits validated Audit Events by appending them to one logical
 * history. Existing committed events are never replaced, modified, or removed;
 * rejected appends leave history unchanged. The observable array order is this
 * log's local append observation only and does not create a distributed total
 * ordering guarantee.
 *
 * @see AUDIT-APPEND-001
 * @see AUDIT-APPEND-002
 * @see AUDIT-APPEND-003
 * @see AUDIT-APPEND-006
 * @see AUDIT-ERROR-001
 */
export class AuditLog {
  private readonly committedEvents: AuditEvent[]
  private readonly committedEventIds: Set<string>

  private constructor(events: readonly AuditEvent[]) {
    this.committedEvents = [...events]
    this.committedEventIds = new Set(events.map((event) => event.eventId))
  }

  /**
   * Creates an Audit Log from existing committed history.
   *
   * Existing history is validated using the same event and duplicate-identity
   * rules as append. No timestamps, identifiers, or ordering metadata are
   * generated by this method.
   *
   * @param history - Existing committed event observations, defaulting to an empty history.
   * @returns An Audit Log containing the supplied committed events.
   * @throws {InvalidAuditEventError}
   * When any supplied event is invalid.
   * @throws {DuplicateAuditEventError}
   * When existing history contains duplicate event identities.
   *
   * @see AUDIT-EVENT-001
   * @see AUDIT-APPEND-003
   */
  static create(history: readonly unknown[] = []): AuditLog {
    if (!Array.isArray(history)) throw new AuditAppendOnlyViolationError()
    const events = history.map((event) => AuditEvent.from(event))
    const ids = new Set<string>()
    for (const event of events) {
      if (ids.has(event.eventId)) throw new DuplicateAuditEventError()
      ids.add(event.eventId)
    }
    return new AuditLog(events)
  }

  /**
   * Appends one valid Audit Event to this logical history.
   *
   * The event is fully validated before history changes. Duplicate event
   * identities are rejected before commit, and failed appends leave previously
   * committed events unchanged.
   *
   * @param eventInput - Candidate Audit Event to commit.
   * @returns This Audit Log after the event is appended.
   * @throws {InvalidAuditEventError}
   * When required event content is missing, malformed, or inconsistent.
   * @throws {InvalidAuditActorError}
   * When supplied known actor attribution is malformed.
   * @throws {DuplicateAuditEventError}
   * When the event identity is already committed in this history.
   *
   * @see FINKORE_AUDIT_INVALID_EVENT
   * @see FINKORE_AUDIT_ACTOR_INVALID
   * @see FINKORE_AUDIT_DUPLICATE_EVENT
   * @see AUDIT-APPEND-001
   * @see AUDIT-APPEND-003
   * @see AUDIT-ERROR-001
   */
  append(eventInput: unknown): AuditLog {
    const event = AuditEvent.from(eventInput)
    if (this.committedEventIds.has(event.eventId)) {
      throw new DuplicateAuditEventError()
    }
    this.committedEvents.push(event)
    this.committedEventIds.add(event.eventId)
    return this
  }

  /**
   * Produces a redacted representation and commits redaction evidence.
   *
   * Redaction preserves the affected event identity, event type, entity
   * reference, timestamp, actor attribution, and unrelated changes. Protected
   * change `before` and `after` values are replaced with an explicit redaction
   * marker that remains distinct from missing values and `null`. The committed
   * source event is not modified; the supplied evidence event is validated and
   * appended as the audit fact that redaction occurred. Failed redactions leave
   * history unchanged.
   *
   * @param request - Policy and evidence event for the redaction action.
   * @returns The redacted affected event and committed evidence event.
   * @throws {InvalidAuditRedactionError}
   * When the policy is malformed, no protected target is found, or redaction
   * would destroy required event meaning.
   * @throws {InvalidAuditEventError}
   * When the evidence event is invalid.
   * @throws {InvalidAuditActorError}
   * When evidence actor attribution is malformed.
   * @throws {DuplicateAuditEventError}
   * When the evidence event identity is already committed.
   *
   * @see FINKORE_AUDIT_REDACTION_INVALID
   * @see FINKORE_AUDIT_DUPLICATE_EVENT
   * @see AUDIT-REDACTION-001
   * @see AUDIT-REDACTION-002
   * @see AUDIT-REDACTION-003
   * @see AUDIT-REDACTION-006
   * @see AUDIT-APPEND-001
   * @see AUDIT-ERROR-001
   */
  redact(request: AuditRedactionRequest): AuditRedactionResult {
    if (request === null || request === undefined) throw new InvalidAuditRedactionError()
    const policy = validateAuditRedactionPolicy(request.policy)
    const evidenceEvent = AuditEvent.from(request.redactionEvent)
    if (this.committedEventIds.has(evidenceEvent.eventId)) {
      throw new DuplicateAuditEventError()
    }

    const candidateEvents = this.committedEvents
      .map((event) => event.toJSON())
      .filter((event) => auditEventMatchesRedactionPolicy(event, policy))

    if (candidateEvents.length !== 1) {
      throw new InvalidAuditRedactionError()
    }

    const sourceEvent = candidateEvents[0]!
    const redactedEvent = redactAuditEvent(sourceEvent, policy)

    this.committedEvents.push(evidenceEvent)
    this.committedEventIds.add(evidenceEvent.eventId)
    return { event: redactedEvent, evidenceEvent: evidenceEvent.toJSON() }
  }

  /**
   * Rejects replacement of a committed Audit Event.
   *
   * FinKore Draft 0.1 currently only permits appending. Replacing committed event content
   * would rewrite logical history and therefore always fails without mutation.
   *
   * @throws {AuditAppendOnlyViolationError}
   * Always, because replacement violates append-only history.
   *
   * @see FINKORE_AUDIT_APPEND_ONLY_VIOLATION
   * @see AUDIT-APPEND-001
   */
  replace(): never {
    throw new AuditAppendOnlyViolationError()
  }

  /**
   * Rejects removal of a committed Audit Event.
   *
   * FinKore Draft 0.1 currently only permits appending. Removing committed event content
   * would erase logical history and therefore always fails without mutation.
   *
   * @throws {AuditAppendOnlyViolationError}
   * Always, because removal violates append-only history.
   *
   * @see FINKORE_AUDIT_APPEND_ONLY_VIOLATION
   * @see AUDIT-APPEND-001
   */
  remove(): never {
    throw new AuditAppendOnlyViolationError()
  }

  /**
   * Returns committed Audit Events as defensive portable observations.
   *
   * @returns Audit history preserving every committed event's identity and meaning.
   *
   * @see AUDIT-APPEND-001
   */
  events(): readonly SerializedAuditEvent[] {
    return this.committedEvents.map((event) => event.toJSON())
  }

  /**
   * Returns the portable conformance shape for this Audit Log.
   *
   * @returns An object containing the committed history observation.
   *
   * @see AUDIT-APPEND-001
   */
  toJSON(): SerializedAuditHistory {
    return { history: this.events() }
  }
}
