import { InvalidApprovalDecisionError } from './errors.js'
import type {
  ApprovalActorIdentifier,
  ApprovalDecisionOutcome,
  ApprovalRequirementIdentifier,
  ApprovalRequirementState,
  SerializedApprovalRequirement,
  SerializedApprovalSubject,
} from './types.js'

function isPlainRecord(value: unknown): value is Readonly<Record<string, unknown>> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function requiredString(value: unknown): string {
  if (typeof value !== 'string' || value.length === 0) throw new InvalidApprovalDecisionError()
  return value
}

function validateOutcome(value: unknown): ApprovalDecisionOutcome {
  if (value !== 'APPROVED' && value !== 'REJECTED') throw new InvalidApprovalDecisionError()
  return value
}

function validateSubject(value: unknown): SerializedApprovalSubject {
  if (!isPlainRecord(value)) throw new InvalidApprovalDecisionError()
  return { type: requiredString(value.type), id: requiredString(value.id) }
}

function validateEligibleActors(value: unknown): readonly ApprovalActorIdentifier[] {
  if (!Array.isArray(value) || value.length === 0) throw new InvalidApprovalDecisionError()
  const actors = value.map(requiredString)
  if (new Set(actors).size !== actors.length) throw new InvalidApprovalDecisionError()
  return actors
}

/**
 * FinKore Approval Requirement for Draft 0.1 requirement representation.
 *
 * A Requirement has a stable caller-supplied identity, identifies the subject
 * whose approval is requested, declares eligible actor identities for this
 * milestone, and defines which Decision outcomes approve or reject it. This
 * class does not implement chains, quorum, delegation, authorization, dynamic
 * actor resolution, persistence, or audit integration.
 *
 * @see APPROVAL-REQUIREMENT-001
 * @see APPROVAL-REQUIREMENT-002
 * @see APPROVAL-REQUIREMENT-003
 * @see APPROVAL-REQUIREMENT-004
 * @see APPROVAL-REQUIREMENT-006
 */
export class ApprovalRequirement {
  private readonly value: SerializedApprovalRequirement

  private constructor(value: SerializedApprovalRequirement) {
    this.value = value
  }

  /**
   * Creates and validates an Approval Requirement from a portable candidate.
   *
   * Requirement identity is preserved exactly as supplied and is never inferred
   * from object position or generated by the implementation.
   *
   * @param input - Candidate serialized Approval Requirement.
   * @returns A validated Approval Requirement value.
   * @throws {InvalidApprovalDecisionError}
   * When required requirement content is missing, malformed, or inconsistent.
   *
   * @see FINKORE_APPROVAL_INVALID_DECISION
   * @see APPROVAL-REQUIREMENT-001
   * @see APPROVAL-REQUIREMENT-002
   * @see APPROVAL-REQUIREMENT-003
   * @see APPROVAL-REQUIREMENT-004
   */
  static from(input: unknown): ApprovalRequirement {
    if (!isPlainRecord(input)) throw new InvalidApprovalDecisionError()
    const approvedOutcome = validateOutcome(input.approvedOutcome)
    const rejectedOutcome = validateOutcome(input.rejectedOutcome)
    if (approvedOutcome === rejectedOutcome) throw new InvalidApprovalDecisionError()
    return new ApprovalRequirement({
      id: requiredString(input.id),
      subject: validateSubject(input.subject),
      eligibleActors: validateEligibleActors(input.eligibleActors),
      approvedOutcome,
      rejectedOutcome,
    })
  }

  /**
   * Stable requirement identity exactly as supplied.
   *
   * @see APPROVAL-REQUIREMENT-001
   */
  get id(): ApprovalRequirementIdentifier {
    return this.value.id
  }

  /**
   * Decision outcome that satisfies this requirement.
   *
   * @see APPROVAL-REQUIREMENT-004
   */
  get approvedOutcome(): ApprovalDecisionOutcome {
    return this.value.approvedOutcome
  }

  /**
   * Decision outcome that rejects this requirement.
   *
   * @see APPROVAL-REQUIREMENT-004
   */
  get rejectedOutcome(): ApprovalDecisionOutcome {
    return this.value.rejectedOutcome
  }

  /**
   * Reports whether a deciding Actor identity is eligible for this requirement.
   *
   * This check is domain eligibility only. It does not model authentication,
   * authorization, RBAC, delegation, or transport permissions.
   *
   * @param actorId - Candidate deciding Actor identity.
   * @returns `true` when the identity is declared eligible.
   *
   * @see APPROVAL-DECISION-004
   * @see APPROVAL-REQUIREMENT-006
   */
  isEligibleActor(actorId: ApprovalActorIdentifier): boolean {
    return this.value.eligibleActors.includes(actorId)
  }

  /**
   * Maps an effective Decision outcome to this Requirement's state.
   *
   * @param outcome - Effective Approval Decision outcome.
   * @returns The resulting Requirement state.
   *
   * @see APPROVAL-REQUIREMENT-004
   */
  stateForOutcome(outcome: ApprovalDecisionOutcome): ApprovalRequirementState {
    if (outcome === this.approvedOutcome) return 'APPROVED'
    if (outcome === this.rejectedOutcome) return 'REJECTED'
    throw new InvalidApprovalDecisionError()
  }

  /**
   * Returns portable Approval Requirement serialization.
   *
   * The returned value is a defensive copy. Mutating it cannot modify this
   * Requirement.
   *
   * @returns Serialized Approval Requirement content.
   *
   * @see APPROVAL-REQUIREMENT-001
   */
  toJSON(): SerializedApprovalRequirement {
    return structuredClone(this.value)
  }
}
